/**
 * Темпы кофе-рана — единственный источник правды о том, из чего человек
 * выбирает на лендинге и что после этого лежит в coffee_run_signups.pace.
 *
 * Читают трое: лендинги (вручную, при вёрстке — три кнопки в форме), API заявки
 * (что вообще можно записать в столбец) и тест, который сверяет одно с другим.
 * Значение — минуты на километр, ровно в том виде, в каком его видит бегун:
 * так строка в базе читается без словаря, а пейсеру не нужно ничего расшифровывать.
 *
 * Новый темп = запись здесь + правка check-констрейнта в миграции 032.
 */
export interface CoffeeRunPace {
  /** То, что ложится в coffee_run_signups.pace: «6:30» — мин/км. */
  value: string;
  /** Слово под цифрой на кнопке — что этот темп значит на бегу. */
  hint: string;
}

/** От быстрого к спокойному — в этом же порядке кнопки стоят в форме. */
export const COFFEE_RUN_PACES: CoffeeRunPace[] = [
  { value: "6:30", hint: "бодрый" },
  { value: "7:00", hint: "ровный" },
  { value: "8:00", hint: "разговорный" },
];

/**
 * Темп из формы → канон, или null, если пришло что-то чужое.
 *
 * null здесь — не ошибка заявки: столбец необязательный, и заявка со старой
 * (закешированной) страницы, где выбора темпа ещё нет, должна сохраниться.
 */
export function normalizePace(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const cleaned = raw.trim();
  return COFFEE_RUN_PACES.some((p) => p.value === cleaned) ? cleaned : null;
}

/** Темп в виде, пригодном для показа человеку: «7:00 мин/км». */
export function formatPace(pace: string): string {
  return `${pace} мин/км`;
}
