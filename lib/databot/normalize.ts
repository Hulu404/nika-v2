/**
 * Нормализация вопроса текстом (ТЗ 4.3, п. 1): нижний регистр, «ё» → «е»,
 * без пунктуации, пробелы схлопнуты. Дальше по этой строке работают все
 * правила разбора — даты, периоды, ключи отчётов, — поэтому они пишутся
 * против одного канонического вида, а не против каждого варианта набора.
 *
 * Точка и дефис — исключение: их оставляем, если с ОБЕИХ сторон буква или
 * цифра. Без точки «03.10» превратилось бы в «03 10», и дата стала бы
 * неотличима от «3 дня» или «в 10»; без дефиса метка IGST-0310 развалилась бы
 * на два слова, а «кофе-ран» перестал бы совпадать с ключом. Точка в конце
 * фразы («за неделю.») и дефис-тире между словами («лужники - суббота») с
 * одной стороны упираются в пробел или край строки — они уходят.
 *
 * Все виды тире (–, —, − и прочие) сначала сводим к дефису: «01.10–07.10»
 * набирают и с длинным тире, и с минусом, а правило «внутри» одинаково для
 * всех — «01.10–07.10» станет «01.10-07.10», «01.10 – 07.10» станет
 * «01.10 07.10». Разбор периодов понимает обе формы.
 *
 * Прочие знаки (запятые, вопросы, кавычки, «№», эмодзи, подчёркивания) не
 * удаляются, а заменяются пробелом: «привет,лужники» — это два слова.
 */

// \u2010–\u2015 — дефисы и тире Unicode, \u2212 — математический минус.
const DASHES_RE = /[\u2010-\u2015\u2212]/g;
// Всё, кроме букв, цифр, пробелов, точки и дефиса.
const JUNK_RE = /[^\p{L}\p{N}\s.-]/gu;
// Комбинируемые знаки, которые остались после NFC. «й» и «ё», набранные
// буквой плюс знаком, NFC уже собрал в одну букву; остаются знаки ударения
// («суббо́та» из словаря или от автозамены) — их убираем без пробела,
// иначе слово распалось бы надвое.
const MARKS_RE = /\p{M}/gu;
// Точка или дефис, у которых хотя бы с одной стороны не буква/цифра.
// Lookbehind смотрит в исходную строку, поэтому «a.-b» теряет оба знака.
const LOOSE_SEP_RE = /(?<![\p{L}\p{N}])[.-]|[.-](?![\p{L}\p{N}])/gu;

export function normalizeText(s: string): string {
  return s
    .normalize("NFC")
    .replace(MARKS_RE, "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(DASHES_RE, "-")
    .replace(JUNK_RE, " ")
    .replace(LOOSE_SEP_RE, " ")
    .replace(/\s+/g, " ")
    .trim();
}
