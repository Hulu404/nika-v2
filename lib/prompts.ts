  morning: `Контекст: сейчас утро перед пробежкой. Человек ещё не побежал — возможно, не хочет, тревожится или сомневается. Помоги ему не давить на себя: снизить ставку, разрешить лёгкий вариант, выйти без чувства, что он «должен». Не уговаривай силой — поддержи намерение.`,

  after_run: `Контекст: человек только что вернулся с пробежки. Помоги ему прожить и закрепить это: разделить, что он чувствует — гордость, усталость, облегчение. Не оценивай результат цифрами. Просто будь рядом с его ощущением.`,

