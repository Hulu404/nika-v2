import { COFFEE_RUNS, dayBefore, REMINDER_HOUR_MSK, type CoffeeRun } from "../coffeerun/run";

/**
 * Когда командный бот пишет сам.
 *
 * Две сводки на забег, обе привязаны не к удобному времени, а к моменту, когда
 * от них ещё есть польза:
 *
 *   eve     — накануне, ПОСЛЕ окна рассылки напоминаний. Смысл один: ушли
 *             напоминания или нет. Прислать это до окна значит прислать «ещё
 *             не отправлено», то есть ничего.
 *   morning — утром в день забега, задолго до сбора. К этому часу список уже
 *             не изменится существенно, а пейсеру надо знать свои группы до
 *             того, как он выйдет из дома.
 *
 * Вся логика «когда» — чистые функции от УЖЕ посчитанных московских даты и
 * часа, по образцу runsDueForReminder и runsDueForInvite: расписание
 * проверяется тестами без подмены системного времени.
 */

/**
 * Час вечерней сводки. На час позже окна напоминаний: рассылка идёт порциями
 * по 25 за проход с паузой в секунду, и к этому моменту она точно закончила.
 * Отчитываться о рассылке, пока она идёт, — верный способ поднять ложную
 * тревогу.
 */
export const EVE_HOUR_MSK = REMINDER_HOUR_MSK + 1;

/**
 * Час утренней сводки. Сбор в 9:30, и 7:00 — это время, когда пейсер ещё дома
 * и может посмотреть свои группы, а не бежит на старт.
 */
export const MORNING_HOUR_MSK = 7;

export type DigestKind = "eve" | "morning";

export interface DueDigest {
  kind: DigestKind;
  run: CoffeeRun;
}

/**
 * Какие сводки пора отправить. Список, а не одна: забеги на разных спотах
 * могут стоять в один день, и вернув только первый мы бы молча оставили
 * половину команды без сводки.
 *
 * `hour >= …`, а не «==»: если тикер проспал свой час (деплой, перезапуск),
 * сводка уйдёт следующим проходом, а не пропадёт совсем. Повторов это не
 * создаёт — их держит таблица team_digests.
 */
export function digestsDue(
  nowYmd: string,
  nowHourMsk: number,
  runs: readonly CoffeeRun[] = COFFEE_RUNS,
): DueDigest[] {
  const due: DueDigest[] = [];

  for (const run of runs) {
    if (run.date === nowYmd && nowHourMsk >= MORNING_HOUR_MSK) {
      due.push({ kind: "morning", run });
    }
    if (dayBefore(run.date) === nowYmd && nowHourMsk >= EVE_HOUR_MSK) {
      due.push({ kind: "eve", run });
    }
  }

  // Вечерняя раньше утренней: если оба забега соседние и оба попали в проход,
  // читать их логичнее в хронологическом порядке.
  return due.sort((a, b) => a.run.date.localeCompare(b.run.date) || (a.kind === "eve" ? -1 : 1));
}
