/**
 * Когда командный бот пишет сам: одна сводка в день, в 8:00 МСК, всем, кто не
 * выключил её через /mute. Если на день ничего не запланировано, сводки нет.
 *
 * `hour >= 8`, а не «== 8»: если тикер проспал свой час (деплой, перезапуск),
 * сводка уйдёт следующим проходом, а не пропадёт. Догоняем только до полудня:
 * «сводка дня» в шесть вечера уже не сводка. Повторов нет — их держит таблица
 * team_digests с ключом по дате.
 *
 * Чистая функция от уже посчитанных московских даты и часа: расписание
 * проверяется тестами без подмены системного времени.
 */

export const DAILY_HOUR_MSK = 8;
export const DAILY_UNTIL_HOUR_MSK = 12;

/** Дата сводки, которую пора отправить, или null. */
export function dailyDigestDue(nowYmd: string, nowHourMsk: number): string | null {
  return nowHourMsk >= DAILY_HOUR_MSK && nowHourMsk < DAILY_UNTIL_HOUR_MSK ? nowYmd : null;
}
