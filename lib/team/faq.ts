/**
 * Быстрые ответы: то, что команда может сказать участнику, ни с кем не
 * сверяясь.
 *
 * Граница проведена намеренно и жёстко. Здесь лежат только факты, которые
 * ПРОВЕРЯЕМЫ по коду и данным: расписание из lib/coffeerun/run.ts, темпы из
 * pace.ts, окна рассылок из reminder/invite-schedule, поведение бота. Всё, что
 * является решением, а не фактом — деньги, партнёрства, перенос и отмена
 * забега, обещания от лица НИКИ, — сюда не попадает и живёт в NEEDS_APPROVAL:
 * бот на такое отвечает «это к организатору», и это честнее выдуманного
 * регламента.
 *
 * Править список — прямо здесь, одним файлом. База под это не нужна: ответы
 * меняются вместе с кодом, который их и порождает, и держать их в базе значило
 * бы иметь два источника правды о расписании.
 */

export interface FaqEntry {
  /** Ключ для /faq <ключ>. Короткий, латиницей — его набирают руками. */
  key: string;
  /** Заголовок в списке — как вопрос звучит вживую. */
  question: string;
  /** По чему ищем при свободном вводе. Нижний регистр, без пунктуации. */
  keywords: string[];
  /**
   * Ответ. Функция, а не строка, ровно потому, что половина ответов — это
   * актуальные дата, адрес и время: продублировать их текстом значило бы
   * однажды прочитать команде прошлогодний адрес.
   */
  answer: (runs: readonly CoffeeRun[]) => string;
}

/** Ссылка на страницу записи конкретного забега (без NEXT_PUBLIC_APP_URL — путь). */
function landingUrl(run: CoffeeRun): string {
  const origin = publicOriginFromEnv();
  return origin ? `${origin}${run.landing}` : run.landing;
}

