/**
 * Вопросы, на которые быстрого ответа НЕ существует. Список короткий и
 * намеренно называет вещи прямо: если человек из команды не уверен, к какой
 * половине относится вопрос, он должен увидеть здесь свой случай, а не гадать.
 */
export const NEEDS_APPROVAL = [
  "деньги: возвраты, скидки, «а можно бесплатно»",
  "перенос, отмена или новое место забега",
  "партнёрства, бренды, съёмки, пресса",
  "обещания от лица НИКИ — призы, места, мерч, гарантии",
  "персональные данные наружу: списки, контакты, статистика кому-то за пределами команды",
];

/** Ответ одного пункта, уже с актуальным расписанием. */
export function faqAnswerText(entry: FaqEntry, now: Date = new Date()): string {
  const runs = upcomingRuns(now);
  return `${entry.question}\n\n${entry.answer(runs)}`;
}

/** /faq без аргумента — оглавление. */
export function faqIndexText(): string {
  return [
    "Быстрые ответы — можно говорить не сверяясь:",
    "",
    ...FAQ.map((e) => `• /faq ${e.key} — ${e.question}`),
    "",
    "А это НЕ быстрые ответы, сначала к организатору:",
    ...NEEDS_APPROVAL.map((n) => `• ${n}`),
  ].join("\n");
}

/**
 * Поиск по ключу или по словам вопроса. Возвращает список: одно совпадение
 * покажем ответом, несколько — уточняющим меню. Пусто — так и скажем, а не
 * подсунем ближайшее по духу: неверный ответ, сказанный уверенно, здесь хуже
 * честного «не знаю».
 */
export function findFaq(query: string): FaqEntry[] {
  const q = query.trim().toLowerCase().replace(/[?!.,]/g, "");
  if (!q) return [];

  const exact = FAQ.find((e) => e.key === q);
  if (exact) return [exact];

  // Запрос-огрызок («а», «не») совпал бы с доброй половиной ключевых слов и
  // вывалил бы весь справочник как «нашла несколько». Короткое ищем только
  // как целое слово запроса, частичное вхождение — от четырёх букв.
  const loose = q.length >= 4;

  return FAQ.filter(
    (e) =>
      e.keywords.some((k) => q.includes(k) || (loose && k.includes(q))) ||
      (loose && e.question.toLowerCase().includes(q)),
  );
}
