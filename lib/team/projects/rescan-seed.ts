/** Пункты сида; ответственные — по нику, если человек уже писал боту. */
export function rescanSeed(ownerOf: (username: string) => number | null): NewRoadmapItem[] {
  return ROWS.map((r, i) => {
    const { owner, ...rest } = r;
    return {
      project_id: RESCAN, kind: rest.kind, code: rest.code, title: rest.title, details: rest.details ?? null,
      group: rest.group ?? null, start_date: rest.start_date ?? null, due_date: rest.due_date ?? null,
      status: "planned", owner_chat_id: owner ? ownerOf(owner) : null, sort: (i + 1) * 10, milestone_code: rest.milestone_code ?? null,
    };
  });
}
