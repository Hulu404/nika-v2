/**
 * Конфиг раздела «Советы» (/tips): словарь категорий + базовые советы для FREE.
 *
 * PRO наполняет страницу личными советами из диалога (personal_tips). FREE видит
 * фиксированный набор BASIC_TIPS (read-only) и не может пополнять её из чата.
 * 'all' в CATEGORY_DEFS означает фильтр «показать все», а не категорию совета.
 */

import type { TipCategory } from "@/types/app";

export type { TipCategory };

export interface CategoryDef {
  /** 'all' это фильтр «Все», прочие id это реальные категории советов. */
  id: "all" | TipCategory;
  label: string;
}

/** Базовый совет для FREE-страницы: статичный, без владельца и удаления. */
export interface BasicTip {
  id: number;
  category: TipCategory;
  title: string;
  body: string;
}

export const CATEGORY_DEFS: CategoryDef[] = [
  { id: "all", label: "Все" },
  { id: "before", label: "Перед бегом" },
  { id: "technique", label: "Техника" },
  { id: "breathing", label: "Дыхание" },
  { id: "gear", label: "Экипировка" },
  { id: "recovery", label: "Восстановление" },
  { id: "mindset", label: "Настрой" },
];

/** Подпись категории по id (включая 'all'). */
export function categoryLabel(id: CategoryDef["id"]): string {
  return CATEGORY_DEFS.find((c) => c.id === id)?.label ?? id;
}

