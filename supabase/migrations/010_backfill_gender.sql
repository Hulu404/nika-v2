-- 010_backfill_gender.sql
-- Уже зарегистрированные пользователи не должны снова проходить онбординг:
-- гейт (isProfileComplete) считает профиль заполненным по gender.
--
-- Кто выбрал женский род — остаётся female и получает женский интерфейс
-- (раздел «Мой ритм»). Кто выбрал мужской или пропустил вопрос (gender IS NULL,
-- поле появилось позже, миграция 005) — получает мужской интерфейс.
--
-- Разовый UPDATE, а не default: у новых регистраций строка profiles заводится
-- лениво с gender IS NULL, поэтому онбординг им по-прежнему показывается.

update public.profiles
   set gender = 'male'
 where gender is null;
