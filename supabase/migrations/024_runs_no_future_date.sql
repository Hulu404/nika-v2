-- 024_runs_no_future_date.sql
-- Баг: пробежку можно было записать на будущую дату. max у <input type="date">
-- в UI — только подсказка браузеру, а пишет журнал клиент напрямую в Postgres
-- через RLS, минуя серверные роуты. Значит валидация обязана жить в БД.
--
-- РЕШЕНИЯ:
--   • Допуск +1 день к current_date: у БД часы в UTC, а дата пробежки — локальная
--     дата пользователя. В UTC+14 «сегодня» на сутки опережает UTC, и жёсткое
--     date <= current_date отклоняло бы честную сегодняшнюю пробежку.
--   • NOT VALID: существующие строки не перепроверяем — если баг уже успел
--     наплодить записей в будущем, миграция не должна падать и не должна молча
--     править данные пользователя. Новые insert/update проверяются в любом случае,
--     поэтому такую запись можно только починить (сдвинуть дату) или удалить.
--   • Идемпотентна: повторный прогон не падает.

alter table public.runs drop constraint if exists runs_date_not_future;

alter table public.runs
  add constraint runs_date_not_future
  check (date <= (current_date + 1))
  not valid;

comment on constraint runs_date_not_future on public.runs is
  'Пробежку записывают постфактум: дата не может быть в будущем (+1 день — допуск на часовые пояса).';
