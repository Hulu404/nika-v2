-- 036_team_digests.sql
-- Сводки, которые командный бот присылает сам: накануне забега (как отработала
-- рассылка напоминаний) и утром в день старта (сколько людей и по каким
-- группам темпа).
--
-- Идемпотентна: create table/index if not exists, add column if not exists,
-- drop policy if exists. Прогон дважды подряд проходит без ошибок.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Кому сводки не нужны
-- ─────────────────────────────────────────────────────────────────────────────
-- По умолчанию включено: человек вошёл в командный бот именно затем, чтобы
-- знать, что происходит. Выключается командой /mute — и это осознанно столбец,
-- а не память процесса: настройка «не пиши мне в 7 утра» обязана пережить
-- деплой, иначе она не настройка.
alter table public.team_members
  add column if not exists digest_opt_in boolean not null default true;

comment on column public.team_members.digest_opt_in is
  'Слать ли этому человеку автоматические сводки (/mute, /unmute)';

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Какие сводки уже отправлены
-- ─────────────────────────────────────────────────────────────────────────────
-- Дедуп в базе, а не в памяти — по той же причине, что у coffee_run_invites
-- (см. 034): тикер делает первый проход сразу при старте процесса, то есть на
-- каждом деплое. С памятью релиз в 7:15 утра в день забега разослал бы
-- утреннюю сводку повторно, а релизы в день забега — обычное дело.
--
-- Ключ — (вид сводки, спот, дата забега): у каждого забега своя утренняя
-- сводка и свой вечерний отчёт, и Усачёва не должна гасить Лужники, даже если
-- забеги попали на один день.
create table if not exists public.team_digests (
  kind     text        not null,   -- 'eve' — накануне, 'morning' — в день забега
  spot     text        not null,
  run_date date        not null,
  sent_at  timestamptz not null default now(),
  -- Скольким ушло. Ноль — сводка построена, но получателей не нашлось
  -- (все через /mute или команда пуста); повторять её всё равно не надо.
  sent_to  integer     not null default 0,
  primary key (kind, spot, run_date)
);

comment on table public.team_digests is
  'Какие автоматические сводки команде уже ушли. Пишет и читает lib/team/digest.ts';

alter table public.team_digests enable row level security;

-- Политик нет: ходит только service_role через бота.

-- Supabase раздаёт anon и authenticated гранты на объекты public-схемы
-- автоматически — снимаем, как в 033, 034 и 035.
revoke all on table public.team_digests from anon, authenticated;
